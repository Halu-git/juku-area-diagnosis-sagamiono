HDR_FONT = Font(color="FFFFFF", bold=True)
BOLD = Font(bold=True)

def add_sheet(name, header, rows, widths=None, notes=None):
    ws = wb.create_sheet(name)
    ws.append(header)
    for c in ws[1]:
        c.fill = HDR_FILL
        c.font = HDR_FONT
    for r in rows:
        ws.append(r)
    if widths:
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
    if notes:
        ws.append([])
        for nt in notes:
            ws.append([nt])
    return ws

